/**
 * Closed evidence and decision formats for the direct `mcpServer/tool/call`
 * feasibility probe. This module owns `<run>/events.jsonl` (append-only,
 * mode 0600, one flat record per line) and validates the frozen decision
 * record consumed by the final report. It is fixed BEFORE any live Host
 * collection: later tasks may select outcomes from the closed vocabularies
 * below but must never add event kinds or open the field allowlists.
 *
 * Record shape: `{version:1, runNonce, sequence, phase, kind, ...kindFields}`.
 * `probeLabel` is a fresh random diagnostic label unique inside the run and
 * `callNonce` is generated by the handler and first appears in
 * `handler-entered`; neither value grants authority. A driver event refers to
 * a callNonce only after a durable join on one unique probeLabel in the run
 * and bounded phase, and the reducer refuses to interpret a driver record as
 * proof of handler or worker settlement. Only closed enums, booleans, bounded
 * counters, field-name/type pairs, and per-run salted hashes are permitted —
 * no generic spread, arbitrary payload, raw ID, or raw path. Null is
 * permitted only where the contract explicitly allows absence
 * (`rpc-observed.callNonce` may be absent until entry; `candidateHashes`
 * values record absence as null).
 *
 * Low-level durable log IO lives in the private `probe-log.mjs` helper;
 * this module owns the vocabulary and the two remaining public write/read
 * surfaces: the driver-scoped appender (which rejects every handler-side
 * kind outright) and the locked reader. The handler-scoped writer is NOT
 * exported from this module — it is a per-instance capability minted inside
 * `createDirectProbeServer` (server.mjs), so driver-side code cannot append
 * handler evidence without instantiating a server.
 *
 * Low-level append/hash/file-lock primitives are reused unchanged from
 * `tools/mcp-context-probe/observer.mjs` and `scripts/lib/fs.mjs`; that
 * module's own schema is not modified.
 */
